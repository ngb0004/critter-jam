/**
 * SUPERSEDED by scripts/delve-pop.ts (parallel, tiered skill + pick policies, gates). Kept for reference; running it
 * overwrites src/delve/bot/population.ts with the old integrator bot table.
 * Real-engine bot population for the "Top N% est." label (BOT / integrator).
 * Usage: npx tsx scripts/delve-population.ts [players=120] [days=314,321]
 * Each simulated player has a skill e (tiered like spec 7.5: 35% casual, 40% average, 25% good), plays 1-3
 * attempts (deterministic per player) with a spec, and keeps the day's best. Writes src/delve/bot/population.ts.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { seedForDay } from '../src/delve/core/daily';
import { Rng } from '../src/delve/core/rng';
import { choose, createWorld, step } from '../src/delve/core/world';
import type { SpecId } from '../src/delve/core/types';
import { buildModifiers } from '../src/delve/content/omens';
import { botChoose, botInput } from '../src/delve/bot/bot';

const players = Number(process.argv[2] ?? 120);
const days = (process.argv[3] ?? '314,321').split(',').map(Number);
const r = new Rng(0xde17e);
const bests: number[] = [];
const t0 = Date.now();
for (const day of days) {
  for (let p = 0; p < players; p++) {
    const u = r.next();
    const tierE = u < 0.35 ? 0.35 : u < 0.75 ? 0.65 : 0.88;
    const e = Math.max(0.1, Math.min(0.99, tierE + (r.next() - 0.5) * 0.2));
    const spec: SpecId = r.next() < 0.5 ? 'ember' : 'venom';
    const attempts = 1 + r.int(3);
    let best = 0;
    for (let a = 0; a < attempts; a++) {
      const seed = seedForDay(day, a);
      const w = createWorld(seed, spec, buildModifiers(seed.omenId, seed.twistId));
      while (!w.over && w.tick < 60 * 60 * 15) {
        if (w.offer.open) {
          choose(w, botChoose(w));
          continue;
        }
        w.events.clear();
        step(w, botInput(w, { e }));
      }
      best = Math.max(best, w.tick / 60);
    }
    bests.push(best);
  }
  console.error(`day ${day} done (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
}
bests.sort((a, b) => a - b);
const q = (p: number): number => bests[Math.min(bests.length - 1, Math.max(0, Math.round((p / 100) * (bests.length - 1))))];
const ps = [0, 1, 5, 10, 25, 50, 75, 90, 95, 99, 100];
const quantiles: [number, number][] = [];
for (const p of ps) {
  let s = Math.round(q(p));
  if (quantiles.length && s <= quantiles[quantiles.length - 1][1]) s = quantiles[quantiles.length - 1][1] + 1;
  quantiles.push([p, s]);
}
if (quantiles[quantiles.length - 1][1] < 872) quantiles.push([100, 872]), (quantiles[quantiles.length - 2][0] = 99.9);
const src = `/**
 * Generated by scripts/delve-population.ts (${players} bot players x days ${days.join(', ')}, tiered skill, 1-3 attempts,
 * daily best). Real-engine survival times in seconds. Regenerate after balance changes.
 */
import type { Population } from '../app/percentile';

export const BOT_POPULATION: Population = {
  source: 'real-engine bots, ${bests.length} daily bests (scripts/delve-population.ts)',
  quantiles: ${JSON.stringify(quantiles)},
};
`;
writeFileSync(resolve(import.meta.dirname, '../src/delve/bot/population.ts'), src);
